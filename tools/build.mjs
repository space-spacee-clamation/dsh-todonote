/**
 * Build dsh-todonote.
 *
 * Host half: `src/host.js` + `src/prompt.js` are copied to `lib/` verbatim —
 * plain ESM, relative imports, no bundler.
 *
 * Client half: the DSH client module system serves `lib/client.js` as a classic
 * script that registers a closure factory:
 *
 *   window.__ModuleLoader__.load({ id: "<pkg>", factory: (require) => { … } })
 *
 * so this script concatenates the (import-free) shared prompt module and the
 * browser source into exactly that wrapper. Nothing else may appear at the top
 * level of the emitted file, and `require` may only ask for platform modules.
 *
 * Usage: node tools/build.mjs
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8')

/** Module specifiers the shell seeds into the frozen module table. */
const PLATFORM_MODULES = new Set([
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
])

const manifest = JSON.parse(read('package.json'))

/** Fail loud instead of shipping a file the module system cannot evaluate. */
function assertNoModuleSyntax(label, source) {
  const match = /^\s*(import|export)\s/m.exec(source)
  if (match !== null) {
    throw new Error(`${label}: top-level "${match[1]}" is not allowed in the factory body`)
  }
}

/** Every `require('…')` inside the browser half must name a platform module. */
function assertPlatformRequires(source) {
  const pattern = /require\(\s*['"]([^'"]+)['"]\s*\)/g
  for (const match of source.matchAll(pattern)) {
    if (!PLATFORM_MODULES.has(match[1])) {
      throw new Error(`src/client.js requires "${match[1]}", which is not a platform module`)
    }
  }
}

const prompt = read('src/prompt.js').replace(/^export /gm, '')
const client = read('src/client.js')

assertNoModuleSyntax('src/prompt.js', read('src/prompt.js').replace(/^export /gm, ''))
assertNoModuleSyntax('src/client.js', client)
assertPlatformRequires(client)

if (!/^function createTodoNotePlugin\(require\)/m.test(client)) {
  throw new Error('src/client.js must define createTodoNotePlugin(require)')
}

const bundle = `// Generated by tools/build.mjs — do not edit.
// Browser half of ${manifest.name}@${manifest.version}: one registration in the
// client module system's factory form, serving the console panel, the sidebar
// glyph and the floating ball.
window.__ModuleLoader__.load({ id: ${JSON.stringify(manifest.name)}, factory: function (require) {
'use strict';
${prompt}
${client}
return createTodoNotePlugin(require);
} });
`

const lib = path.join(root, 'lib')
fs.mkdirSync(lib, { recursive: true })
fs.copyFileSync(path.join(root, 'src/host.js'), path.join(lib, 'index.js'))
fs.copyFileSync(path.join(root, 'src/prompt.js'), path.join(lib, 'prompt.js'))
fs.writeFileSync(path.join(lib, 'client.js'), bundle)

const bytes = (relative) => fs.statSync(path.join(root, relative)).size
console.log(`Built ${manifest.name}@${manifest.version}:`)
console.log(`  lib/index.js   ${bytes('lib/index.js')} bytes  (host half)`)
console.log(`  lib/prompt.js  ${bytes('lib/prompt.js')} bytes  (shared prompt contract)`)
console.log(`  lib/client.js  ${bytes('lib/client.js')} bytes  (browser half, ${PLATFORM_MODULES.size} platform externals allowed)`)
